#!/usr/bin/env python3
"""Generate the small C header the Android wrapper needs.

The module_start address lives in the game's own analysis JSON produced by `vitarecomp add`.
Keeping it out of Java means a rebuilt/re-analysed game only needs a native rebuild.
"""
import argparse
import json
import os
import sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    tomllib = None


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--nativ-root", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--title", default="PCSG00615")
    ap.add_argument("--version", default="1.00")
    args = ap.parse_args()

    nativ = os.path.abspath(args.nativ_root)
    analysis = os.path.join(nativ, "dump", "decrypted", args.title, "analysis", "eboot.data.json")
    pack = os.path.join(nativ, "packs", args.title, "pack.toml")

    entry = None
    if os.path.isfile(analysis):
        try:
            with open(analysis, "r", encoding="utf-8") as f:
                data = json.load(f)
            value = data.get("functions", {}).get("module_start")
            if value:
                entry = f"0x{int(value) & ~1:08x}"
        except (OSError, ValueError, TypeError) as exc:
            print(f"gen_jail_config: cannot read {analysis}: {exc}", file=sys.stderr)

    name = "東京喰種トーキョーグール JAIL"
    version = args.version
    if tomllib and os.path.isfile(pack):
        try:
            with open(pack, "rb") as f:
                conf = tomllib.load(f)
            name = conf.get("NAME", name)
            versions = conf.get("versions", {})
            if versions:
                version = next(iter(versions))
        except (OSError, ValueError, TypeError) as exc:
            print(f"gen_jail_config: cannot read {pack}: {exc}", file=sys.stderr)

    if not entry:
        # This is the value measured for PCSG00615 1.00 in this repository. It is only a fallback
        # for a checkout that has not run the desktop analysis yet.
        entry = "0x81081fdc"
        print(f"gen_jail_config: no {analysis}; using known PCSG00615 entry {entry}", file=sys.stderr)

    out = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* generated by android/scripts/gen_jail_config.py -- do not edit */\n")
        f.write("#ifndef JAIL_CONFIG_H\n#define JAIL_CONFIG_H\n\n")
        f.write(f"#define JAIL_GAME_ENTRY   {c_string(entry)}\n")
        f.write(f"#define JAIL_TITLE_ID     {c_string(args.title)}\n")
        f.write(f"#define JAIL_GAME_NAME    {c_string(name)}\n")
        f.write(f"#define JAIL_GAME_VERSION {c_string(version)}\n")
        f.write("\n#endif\n")
    print(f"gen_jail_config: {args.title} {version}, entry {entry}, name {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
